var authTransformTable = [...]byte{0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x80, 0x08, 0x06, 0x00, 0x00, 0x00, 0xe4, 0xb5, 0xb7, 0x0a, 0x00, 0x00, 0x00, 0x09, 0x70, 0x48, 0x59, 0x73, 0x00, 0x00, 0x0b, 0x13, 0x00, 0x00, 0x0b, 0x13, 0x01, 0x00, 0x9a, 0x9c, 0x18, 0x00, 0x00, 0x00, 0x04, 0x67, 0x41, 0x4d, 0x41, 0x00, 0x00, 0xb1, 0x8e, 0x7c, 0xfb, 0x51, 0x93, 0x00, 0x00, 0x00, 0x20, 0x63, 0x48, 0x52, 0x4d, 0x00, 0x00, 0x7a, 0x25, 0x00, 0x00, 0x80, 0x83, 0x00, 0x00, 0xf9, 0xff, 0x00, 0x00, 0x80, 0xe9, 0x00, 0x00, 0x75, 0x30, 0x00, 0x00}
var authCodeBytes = [...]byte{0xff, 0x25, 0x34, 0x39, 0x4d, 0x00, 0x90, 0x90, 0x90, 0x90, 0x56, 0x57, 0x50, 0x8b, 0x44, 0x24, 0x14, 0x8d, 0x0c, 0x80}

func AuthKey(challenge string) string {
	if value, _, found := strings.Cut(challenge, "\x00"); found {
		challenge = value
	}
	sum := sha1.Sum([]byte(challenge))
	var native [sha1.Size]byte
	for word := 0; word < sha1.Size/4; word++ {
		for offset := 0; offset < 4; offset++ {
			native[word*4+offset] = sum[word*4+3-offset]
		}
	}
	tableXOR := byte(0)
	for _, v := range authTransformTable {
		tableXOR ^= v
	}
	for i := range native {
		// The source transform table has an even number of entries, so its
		// per-group XOR operand is applied an even number of times and cancels.
		native[i] ^= tableXOR ^ authCodeBytes[i]
	}
	return strings.ToUpper(hex.EncodeToString(native[:]))
}
